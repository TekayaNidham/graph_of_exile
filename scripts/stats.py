"""Generate dataset/STATS.md and dataset/stats.json from the built dataset.
Usage: python3 -I scripts/stats.py"""
import json, os
from collections import Counter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
D = os.path.join(ROOT, "dataset")
out, md = {}, ["# Dataset statistics", "", "_Generated by `scripts/stats.py` — do not edit by hand._", ""]
for v, title in (("master", "Master (everything)"), ("poe1", "Path of Exile 1"), ("poe2", "Path of Exile 2")):
    n = json.load(open(os.path.join(D, v, "nodes.json")))
    e = json.load(open(os.path.join(D, v, "edges.json")))
    s = json.load(open(os.path.join(D, v, "sources.json")))
    spine = [x for x in e if x["relation"] == "next_beat"]
    st = {
        "nodes": len(n), "edges": len(e), "sources": len(s), "spine_beats": len({x["source"] for x in spine} | {x["target"] for x in spine}),
        "by_type": Counter(x["type"] for x in n), "by_plot_role": Counter(x["plot_role"] for x in n),
        "by_era": Counter(x["era"] for x in n), "by_branch": Counter(b for x in n for b in x.get("branches", [])),
        "by_relation": Counter(x["relation"] for x in e), "by_source_type": Counter(x["type"] for x in s),
        "by_source_reliability": Counter(x["reliability"] for x in s), "by_confidence": Counter(x["confidence"] for x in n),
        "by_canon_status": Counter(x["canon_status"] for x in n), "by_release_status": Counter(x.get("release_status", "released") for x in n),
    }
    out[v] = st
    md += [f"## {title} (`dataset/{v}/`)", "",
           f"**{st['nodes']:,} nodes · {st['edges']:,} edges · {st['sources']:,} sources · {st['spine_beats']} Exile-journey beats**", ""]
    for key, label in (("by_plot_role", "Plot role"), ("by_type", "Node type"), ("by_era", "Era"), ("by_confidence", "Confidence"),
                       ("by_canon_status", "Canon status"), ("by_release_status", "Release status"), ("by_source_reliability", "Source reliability")):
        md.append(f"<details><summary>{label}</summary>\n\n| value | count |\n|---|---:|")
        md += [f"| {k} | {c} |" for k, c in st[key].most_common()]
        md.append("\n</details>\n")
    md.append("<details><summary>Branches / leagues</summary>\n\n| branch | nodes |\n|---|---:|")
    md += [f"| {k} | {c} |" for k, c in st["by_branch"].most_common()]
    md.append("\n</details>\n")
    md.append("<details><summary>Relations</summary>\n\n| relation | edges |\n|---|---:|")
    md += [f"| {k} | {c} |" for k, c in st["by_relation"].most_common()]
    md.append("\n</details>\n")
json.dump(out, open(os.path.join(D, "stats.json"), "w"), indent=1)
open(os.path.join(D, "STATS.md"), "w").write("\n".join(md) + "\n")
m = out["master"]
print(f"master: {m['nodes']} nodes, {m['edges']} edges, {m['sources']} sources; branches={len(m['by_branch'])}; relations={len(m['by_relation'])}")
print("poe1:", out["poe1"]["nodes"], out["poe1"]["edges"], "poe2:", out["poe2"]["nodes"], out["poe2"]["edges"])
print(dict(m["by_plot_role"]))
print(dict(m["by_source_type"]))
